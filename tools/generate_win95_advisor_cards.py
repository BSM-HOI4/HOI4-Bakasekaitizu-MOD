#!/usr/bin/env python3
"""Generate standalone Win95 advisor backgrounds; never overwrite native sprite IDs."""
import argparse
import hashlib
import io
import json
from pathlib import Path
from PIL import Image, ImageDraw
from win95_gui_lib import nodes, value

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'bakasekai'
ASSETS = MOD / 'gfx/interface/win95/advisors'
GFX = MOD / 'interface/_bsm_win95_advisor_cards.gfx'
GUIS = [MOD / 'interface/replace/countrypoliticsview.gui', MOD / 'interface/BSM_countryinfoview.gui']
SPECS = [('GFX_idea_entry_bg_2', 'GFX_bsm_win95_advisor_entry_grid', 231, 'entry_grid.png'),
         ('GFX_idea_entry_bg_3', 'GFX_bsm_win95_advisor_entry_list', 462, 'entry_list.png')]


def render(width):
    image = Image.new('RGBA', (width * 2, 96), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    for frame in range(2):
        x = frame * width
        face = '#dbe9f9' if frame else '#ffffff'
        draw.rectangle((x, 0, x + width - 1, 95), fill='#808080')
        draw.line((x, 0, x + width - 1, 0), fill='#ffffff')
        draw.line((x, 0, x, 95), fill='#ffffff')
        draw.line((x + width - 1, 1, x + width - 1, 95), fill='#404040')
        draw.line((x + 1, 95, x + width - 1, 95), fill='#404040')
        draw.rectangle((x + 2, 2, x + width - 3, 93), fill=face)
        if frame:
            draw.rectangle((x + 2, 2, x + width - 3, 93), outline='#000080', width=2)
    buf = io.BytesIO()
    image.save(buf, format='PNG', optimize=False)
    return buf.getvalue()


def outputs():
    # Definition props and frame geometry have been verified against active native IDs.
    source = MOD / 'interface/replace/countrypoliticsview.gfx'
    source_text = source.read_text(encoding='utf-8-sig')
    defs = {value(source_text, n, 'name'): n for n in nodes(source_text) if n.key == 'spriteType'}
    result = {}
    gfx = ['# Generated by tools/generate_win95_advisor_cards.py', 'spriteTypes = {']
    entries = []
    for old, new, width, filename in SPECS:
        n = defs[old]
        assert value(source_text, n, 'noOfFrames') == '2'
        # Clone original definition including any native effect/border props.
        text = source_text[n.start:n.end]
        text = text.replace('"' + old + '"', '"' + new + '"', 1)
        texture = value(source_text, n, 'texturefile')
        text = text.replace('"' + texture + '"', '"gfx/interface/win95/advisors/' + filename + '"', 1)
        gfx.append('\t' + text.replace('\n', '\n\t'))
        data = render(width)
        result[ASSETS / filename] = data
        entries.append({'source_sprite': old, 'sprite': new, 'file': filename,
                        'frame_width': width, 'height': 96, 'frames': 2,
                        'sha256': hashlib.sha256(data).hexdigest()})
    gfx.append('}')
    result[GFX] = ('\n'.join(gfx) + '\n').encode()
    result[ASSETS / 'manifest.json'] = (json.dumps({'generator': 'tools/generate_win95_advisor_cards.py',
        'assets': entries, 'states': ['white normal', 'pale blue selected with navy outline'],
        'disabled': 'Existing engine disabled-state rendering retained; native frame count unchanged.',
        'alpha': 'Opaque blank card faces; portraits and companies remain separate GUI children.'}, indent=2) + '\n').encode()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.apply == args.check:
        parser.error('Choose exactly one of --apply or --check')
    expected = outputs()
    for p, data in expected.items():
        if args.apply:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
        else:
            assert p.read_bytes() == data, str(p)
    for p in GUIS:
        text = p.read_text(encoding='utf-8-sig')
        if args.apply:
            for old, new, _, _ in SPECS:
                text = text.replace('"' + old + '"', '"' + new + '"')
            p.write_text(text, encoding='utf-8')
        nodes(text)
        for old, new, _, _ in SPECS:
            assert '"' + old + '"' not in text
            assert '"' + new + '"' in text
    gfx = GFX.read_text()
    nodes(gfx)
    for _, new, width, filename in SPECS:
        image = Image.open(ASSETS / filename)
        assert image.size == (width * 2, 96)
        assert image.mode == 'RGBA'
        assert new in gfx
    print('PASS: 2 PNG dimensions/frames, deterministic assets, closed GFX, 2 GUI references/parser')


if __name__ == '__main__':
    main()
