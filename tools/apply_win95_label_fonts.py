#!/usr/bin/env python3
"""Scope black font clones to light shared chrome; keep dark subpanels unchanged."""
from pathlib import Path
import json
import re
ROOT=Path(__file__).resolve().parents[1]; MOD=ROOT/'bakasekai'
TOKEN=re.compile(r'#[^\n]*|"(?:\\.|[^"\\])*"|[{}]|[^\s{}=#"]+|=')
def nodes(text):
    out=[]; stack=[]; prev=[]
    for m in TOKEN.finditer(text):
        t=m[0]
        if t.startswith('#'):continue
        if t=='{':
            key=prev[-2][0] if len(prev)>1 and prev[-1][0]=='=' else ''
            n=dict(key=key,start=m.start(),end=None,children=[],parent=stack[-1] if stack else None)
            if stack: stack[-1]['children'].append(n)
            stack.append(n);out.append(n)
        elif t=='}':
            assert stack, 'unbalanced brace'
            stack.pop()['end']=m.end()
        prev.append((t,m.start()));prev=prev[-2:]
    assert not stack
    return out

def shallow(text,node):
    s=text[node['start']:node['end']]
    for c in reversed(node['children']):
        a=c['start']-node['start'];b=c['end']-node['start'];s=s[:a]+' '*(b-a)+s[b:]
    return s
manifest=json.loads((MOD/'gfx/interface/win95/shared/manifest.json').read_text())
light={r['name'] for r in manifest if 'header' not in r['name']}
fonts={};overrides={}
base=Path.home()/'Library/Application Support/Steam/steamapps/common/Hearts of Iron IV/interface/core.gfx'
for p in [base,*sorted((MOD/'interface').rglob('*.gfx'))]:
    if p.name=='_bsm_win95_shared_fonts.gfx':continue
    text=p.read_text(encoding='utf-8-sig')
    for n in nodes(text):
        if n['key'] not in ('bitmapfont','bitmapfont_override'):continue
        name=re.search(r'\bname\s*=\s*"([^"]+)"',shallow(text,n))
        if not name:continue
        block=text[n['start']:n['end']]
        if n['key']=='bitmapfont':
            fonts[name[1]]=block
            overrides[name[1]]=[]
        else:overrides.setdefault(name[1],[]).append(block)
used=set();changed={}
for p in sorted((MOD/'interface').rglob('*.gui')):
    text=p.read_text(encoding='utf-8-sig'); ns=nodes(text); replacements=[]
    for n in ns:
        local=shallow(text,n)
        fm=re.search(r'\b(?:font|buttonFont)\s*=\s*"([^"]+)"',local)
        if not fm:continue
        original=fm[1]
        if original.startswith('bsm_w95_') and original.endswith('_black'):continue
        sprite=re.search(r'(?:quadTextureSprite|spriteType)\s*=\s*"([^"]+)"',local)
        islight=bool(sprite and sprite[1] in light)
        if not sprite:
            parent=n['parent']
            while parent:
                backgrounds=[c for c in parent['children'] if c['key'].lower()=='background']
                if backgrounds:
                    bg=shallow(text,backgrounds[0]);sp=re.search(r'(?:quadTextureSprite|spriteType)\s*=\s*"([^"]+)"',bg)
                    if sp and sp[1]:
                        islight=sp[1] in light;break
                parent=parent['parent']
        if not islight or original not in fonts:continue
        # Titles sit on separate navy header textures even inside a light window.
        if 'header' in original or 'title' in (re.search(r'\bname\s*=\s*"([^"]+)"',local)[1] if re.search(r'\bname\s*=\s*"([^"]+)"',local) else ''):continue
        used.add(original);new='bsm_w95_'+original+'_black'
        replacements.append((n['start']+fm.start(1),n['start']+fm.end(1),new))
    for a,b,new in sorted(replacements,reverse=True):text=text[:a]+new+text[b:]
    if replacements:p.write_text(text,encoding='utf-8');changed[str(p.relative_to(ROOT))]=len(replacements)
# Retain already-used clones when rerunning.
for p in (MOD/'interface').rglob('*.gui'):
    used.update(re.findall(r'(?:font|buttonFont)\s*=\s*"bsm_w95_(.*?)_black"',p.read_text(encoding='utf-8-sig')))
output=['# Generated by tools/apply_win95_label_fonts.py. Exact source glyphs/metrics retained.','bitmapfonts = {']
for name in sorted(used):
    clone='bsm_w95_'+name+'_black'
    block=re.sub(r'(\bname\s*=\s*")[^"]+',lambda m:m[1]+clone,fonts[name],count=1)
    block=re.sub(r'(?m)^(\s*color\s*=\s*)[^\n]+',r'\g<1>0xff000000',block,count=1)
    output.append('  bitmapfont = '+block)
    for override in overrides.get(name,[]):
        block=re.sub(r'(\bname\s*=\s*")[^"]+',lambda m:m[1]+clone,override,count=1)
        output.append('  bitmapfont_override = '+block)
output.append('}')
(MOD/'interface/_bsm_win95_shared_fonts.gfx').write_text('\n'.join(output)+'\n')
print(f'PASS: {sum(changed.values())} labels in {len(changed)} GUI files; {len(used)} black font clones')
for p,n in changed.items():print(f'{n:3} {p}')
